"""Generate the in-app notes from the same versioned source used for Play."""
from pathlib import Path
import json
import re

from tool.publish_play import parse_release_notes, pubspec_version

OUTPUT = Path('lib/data/preferences/current_release.g.dart')


def dart_string(value):
    escaped = json.dumps(value, ensure_ascii=False)[1:-1]
    return "'" + escaped.replace("'", "\\'").replace('$', '\\$') + "'"


def generate(root):
    version, _ = pubspec_version(root)
    if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+', version):
        raise ValueError('In-app notes require a stable major.minor.patch version.')
    notes = parse_release_notes(root / 'docs/releases' / f'{version}.md')
    lines = [
        '// Generated by python3 -m tool.generate_release_notes. Do not edit.',
        f'const currentReleaseVersion = {dart_string(version)};',
        '',
        'const currentReleaseNotes = <String, String>{',
    ]
    for locale, body in notes.items():
        key = dart_string(locale.split('-')[0])
        value = dart_string(body)
        lines.append(f'  {key}: {value},')
    lines.extend(['};', ''])
    output = root / OUTPUT
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    generate(Path.cwd())
