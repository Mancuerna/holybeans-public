/// Folds the supported precomposed Latin accents in one UTF-16 code unit.
int foldLatinAccent(int code) => switch (code) {
  0xe0 || 0xe1 || 0xe2 || 0xe3 || 0xe4 => 97,
  0xe8 || 0xe9 || 0xea || 0xeb => 101,
  0xec || 0xed || 0xee || 0xef => 105,
  0xf2 || 0xf3 || 0xf4 || 0xf5 || 0xf6 => 111,
  0xf9 || 0xfa || 0xfb || 0xfc => 117,
  0xf1 => 110,
  0xe7 => 99,
  _ => code,
};
